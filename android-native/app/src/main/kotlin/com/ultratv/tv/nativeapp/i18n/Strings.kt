/**
 * Langue de l'interface, indépendante de la langue du système ([System] = automatique). Ajouter une langue :
 * un dossier `res/values-xx/strings.xml` + une entrée ici (code, nom affiché dans sa langue, sens d'écriture) ;
 * le sélecteur des Réglages lit cette liste, les écrans n'ont rien à changer. Une clé absente d'une langue
 * affiche l'anglais (res/values), la langue source. Voir [I18n].
 */
enum class AppLang(val code: String, val displayName: String, val rtl: Boolean = false) {
    System("system", "System (auto)"),
    English("en", "English"),
    French("fr", "Français"),
    Spanish("es", "Español"),
    Arabic("ar", "العربية", rtl = true),
    // Langue communautaire (premier jet, à relire via Weblate).
    Polish("pl", "Polski");

    companion object {
        fun fromCode(code: String): AppLang = entries.firstOrNull { it.code == code } ?: System
    }
}

