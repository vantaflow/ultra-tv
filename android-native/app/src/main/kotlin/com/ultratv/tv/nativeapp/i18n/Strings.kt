/** Textes de l'interface pour une langue (cache par langue résolue). Utilisable hors Compose. */
fun stringsOf(lang: AppLang): Strings {
    val resolved = I18n.resolve(lang)
    return I18n.cached("Strings", resolved) { buildStrings(resolved) }
}

@Composable
fun stringsFor(lang: AppLang): Strings {
    // Lecture de la configuration : recompose quand la langue de l'appareil change (mode Automatique).
    LocalConfiguration.current
    return stringsOf(lang)
}

val LocalStrings = compositionLocalOf<Strings> { stringsOf(AppLang.English) }
