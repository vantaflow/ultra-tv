export const SITE_LANGS = ["en", "fr", "es", "ar", "pl"];
export const SITE_DEFAULT_LANG = "en";
export const SITE_COOKIE = "utv-lang";
export const SITE_LANG_NAMES = { en: "English", fr: "Français", es: "Español", ar: "العربية", pl: "Polski" };
export const SITE_DIR = { en: "ltr", fr: "ltr", es: "ltr", ar: "rtl", pl: "ltr" };

