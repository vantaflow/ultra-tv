/** Code de langue normalisé (ex. "en-US" -> "en") ou null si non supporté. */
export function normalizeSiteLang(tag) {
  if (typeof tag !== "string") return null;
  const primary = tag.trim().toLowerCase().split(/[-_]/)[0];
  return SITE_LANGS.includes(primary) ? primary : null;
}

/** Analyse l'en-tête Accept-Language en respectant les pondérations q=. */
export function fromAcceptLanguage(header) {
  if (typeof header !== "string" || !header) return null;
  const items = header.split(",").map((part, i) => {
    const [tag, ...params] = part.trim().split(";");
    let q = 1;
    for (const p of params) {
      const m = p.trim().match(/^q\s*=\s*([0-9.]+)$/i);
      if (m) q = Number.parseFloat(m[1]);
    }
    return { tag: tag.trim(), q: Number.isFinite(q) ? q : 0, i };
  });
  items.sort((a, b) => b.q - a.q || a.i - b.i);
  for (const it of items) {
    if (it.q <= 0) continue;
    const l = normalizeSiteLang(it.tag);
    if (l) return l;
  }
  return null;
}

/** Lit le cookie utv-lang depuis l'en-tête Cookie. */
export function langFromCookie(cookieHeader) {
  if (typeof cookieHeader !== "string") return null;
  for (const part of cookieHeader.split(";")) {
    const eq = part.indexOf("=");
    if (eq > 0 && part.slice(0, eq).trim() === SITE_COOKIE) return normalizeSiteLang(part.slice(eq + 1).trim());
  }
  return null;
}

/** Résout la langue d'une requête : paramètre ?l= > cookie utv-lang > Accept-Language > défaut. */
export function pickSiteLang({ param = null, cookie = null, acceptLanguage = null } = {}, defaultLang = SITE_DEFAULT_LANG) {
  return normalizeSiteLang(param) || normalizeSiteLang(cookie) || fromAcceptLanguage(acceptLanguage) || defaultLang;
}

/** Génère les liens HTML du sélecteur de langue pour une URL donnée. */
export function langLinks(rawUrl = "/", currentLang = "fr") {
  let pathname = "/";
  let params = new URLSearchParams();
  try {
    const u = new URL(rawUrl, "https://ultratv.dpdns.org");
    pathname = u.pathname;
    params = new URLSearchParams(u.search);
  } catch {
    const qIndex = String(rawUrl).indexOf("?");
    pathname = qIndex >= 0 ? rawUrl.slice(0, qIndex) : rawUrl || "/";
    if (qIndex >= 0) params = new URLSearchParams(rawUrl.slice(qIndex + 1));
  }
  return SITE_LANGS.map((l) => {
    const sp = new URLSearchParams(params);
    sp.set("l", l);
    const qs = sp.toString();
    const href = `${pathname}${qs ? `?${qs}` : ""}`;
    return `<a href="${e(href)}" data-lang="${l}" lang="${l}" hreflang="${l}"${l === currentLang ? ' aria-current="true"' : ""}>${e(SITE_LANG_NAMES[l])}</a>`;
  }).join("");
}

